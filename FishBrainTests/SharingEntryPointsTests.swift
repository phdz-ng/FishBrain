import XCTest

final class ImportFileTests: XCTestCase {
    func testWhichFilesAreImportable() {
        for name in ["a.csv", "A.CSV", "list.tsv", "notes.txt", "Spanish A1.apkg", "deck.APKG"] {
            XCTAssertTrue(ImportFile.isImportable(URL(fileURLWithPath: "/tmp/\(name)")), name)
        }
        for name in ["a.pdf", "a.png", "a.csv.zip", "noextension", "a.apkg.txt.bak"] {
            XCTAssertFalse(ImportFile.isImportable(URL(fileURLWithPath: "/tmp/\(name)")), name)
        }
        XCTAssertFalse(ImportFile.isImportable(URL(string: "https://example.com/a.csv")!), "only files on this Mac")
    }
}

@MainActor
final class OpeningFilesTests: XCTestCase {
    func testAnOpenedCSVOrPackageAsksTheWindowToImportIt() {
        let router = DeepLinkRouter()
        let csv = URL(fileURLWithPath: "/tmp/Spanish.csv")
        XCTAssertTrue(router.handle(csv))
        XCTAssertEqual(router.pendingImportURL, csv)
        XCTAssertNil(router.pendingDeckID)

        let package = URL(fileURLWithPath: "/tmp/Spanish A1.apkg")
        XCTAssertTrue(router.handle(package))
        XCTAssertEqual(router.pendingImportURL, package)
    }

    func testOtherFilesAreLeftAlone() {
        let router = DeepLinkRouter()
        XCTAssertFalse(router.handle(URL(fileURLWithPath: "/tmp/photo.png")))
        XCTAssertNil(router.pendingImportURL)
    }

    func testDeckLinksStillWork() {
        let router = DeepLinkRouter()
        let id = UUID()
        XCTAssertTrue(router.handle(DeepLink.deck(id)))
        XCTAssertEqual(router.pendingDeckID, id)
        XCTAssertNil(router.pendingImportURL)
    }

    func testAnOpenedFileReadsIntoThePreview() throws {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("opened-\(UUID().uuidString).csv")
        defer { try? FileManager.default.removeItem(at: url) }
        try Data("Front,Back,Deck\nhola,hello,Spanish\n".utf8).write(to: url)

        let router = DeepLinkRouter()
        XCTAssertTrue(router.handle(url))
        let opened = try XCTUnwrap(router.pendingImportURL)
        let table = try CSVTable.read(contentsOf: opened).get()
        XCTAssertEqual(table.columnCount, 3)
        XCTAssertTrue(table.looksLikeHeader)
    }
}

final class SharingMenuRulesTests: XCTestCase {
    func testFileMenuExportCoversTheSubjectThenTheDeckThenTheLibrary() {
        let subject = Subject(name: "Spanish"), deck = Deck(name: "Verbs")
        XCTAssertEqual(ExportTarget.current(subjectID: subject.id, deckID: deck.id), .subject(subject.id))
        XCTAssertEqual(ExportTarget.current(subjectID: nil, deckID: deck.id), .deck(deck.id))
        XCTAssertEqual(ExportTarget.current(subjectID: nil, deckID: nil), .library)
    }

    func testExportIsOffUntilThereAreCardsToExport() {
        let empty = Deck(name: "Empty")
        let full = Deck(name: "Full", cards: [Card(front: "a", back: "b")])
        let reason = { (target: ExportTarget, decks: [Deck]) in
            ExportDraft(target: target).unavailableReason(subjects: [], decks: decks)
        }
        XCTAssertNotNil(reason(.library, []))
        XCTAssertNotNil(reason(.library, [empty]))
        XCTAssertNil(reason(.library, [empty, full]))
        XCTAssertNotNil(reason(.deck(empty.id), [empty, full]))
        XCTAssertNil(reason(.deck(full.id), [empty, full]))
    }

    func testTheSidebarNewMenuEndsWithImport() {
        let item = NewMenu.importItem
        XCTAssertEqual(item.action, .importFile)
        XCTAssertEqual(item.title, "Import…")
        XCTAssertEqual(item.shortcut, "⇧⌘I")
        XCTAssertTrue(item.isEnabled)

        // The subject page's own New menu filters to "New … in", and the base list has no Import.
        let tree = SubjectTree([Subject(name: "Spanish")])
        XCTAssertFalse(NewMenu.items(in: nil, tree: tree).contains { $0.action == .importFile })
    }
}

final class InfoPlistDocumentTypesTests: XCTestCase {
    private func plist() throws -> [String: Any] {
        // The generated Info.plist next to the app's sources (regenerated by `xcodegen generate`).
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("FishBrain/Info.plist")
        let data = try Data(contentsOf: url)
        return try XCTUnwrap(PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any])
    }

    func testTheAppDeclaresTheFilesItCanImport() throws {
        let info = try plist()
        let types = try XCTUnwrap(info["CFBundleDocumentTypes"] as? [[String: Any]])
        let declared = Set(types.flatMap { $0["LSItemContentTypes"] as? [String] ?? [] })
        XCTAssertTrue(declared.contains("public.comma-separated-values-text"))
        XCTAssertTrue(declared.contains("public.tab-separated-values-text"))
        XCTAssertTrue(declared.contains { $0.hasSuffix(".apkg") })
        // Offered, never taken over from Numbers, Excel or Anki.
        XCTAssertTrue(types.allSatisfy { $0["LSHandlerRank"] as? String == "Alternate" })
        XCTAssertTrue(types.allSatisfy { $0["CFBundleTypeRole"] as? String == "Viewer" })
    }

    func testTheAnkiPackageTypeIsDeclaredByExtension() throws {
        let info = try plist()
        let imported = try XCTUnwrap(info["UTImportedTypeDeclarations"] as? [[String: Any]])
        let apkg = try XCTUnwrap(imported.first { ($0["UTTypeIdentifier"] as? String)?.hasSuffix(".apkg") == true })
        let tags = try XCTUnwrap(apkg["UTTypeTagSpecification"] as? [String: Any])
        XCTAssertEqual(tags["public.filename-extension"] as? [String], ["apkg"])
        XCTAssertTrue((apkg["UTTypeConformsTo"] as? [String] ?? []).contains("public.zip-archive"))
    }
}
